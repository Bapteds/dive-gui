/** blockMeshDict: a single hex background box, sized from the resolved domain. */
export function renderBlockMeshDict(domain: SnappyDomain): string {
  const [x0, y0, z0] = domain.boxMin;
  const [x1, y1, z1] = domain.boxMax;
  const [nx, ny, nz] = domain.counts;
  const v = (x: number, y: number, z: number) => `    (${fmt(x)} ${fmt(y)} ${fmt(z)})`;
  return `${foamHeader('dictionary', 'blockMeshDict', 'system')}
scale 1;

vertices
(
${v(x0, y0, z0)}
${v(x1, y0, z0)}
${v(x1, y1, z0)}
${v(x0, y1, z0)}
${v(x0, y0, z1)}
${v(x1, y0, z1)}
${v(x1, y1, z1)}
${v(x0, y1, z1)}
);

blocks
(
    hex (0 1 2 3 4 5 6 7) (${nx} ${ny} ${nz}) simpleGrading (1 1 1)
);

edges ();

boundary
(
    domainBoundary
    {
        type patch;
        faces
        (
            (0 3 2 1)
            (4 5 6 7)
            (0 1 5 4)
            (2 3 7 6)
            (1 2 6 5)
            (0 4 7 3)
        );
    }
);

mergePatchPairs ();
${FOOTER}`;
}

/** surfaceFeatureExtractDict: one feature-extraction block per STL region. */
export function renderSurfaceFeatureExtractDict(stlNames: string[]): string {
  const blocks = stlNames
    .map(
      (name) => `${name}
{
    extractionMethod    extractFromSurface;
    extractFromSurfaceCoeffs { includedAngle 150; }
    subsetFeatures { nonManifoldEdges no; openEdges yes; }
    writeObj no;
}`,
    )
    .join('\n\n');
  return `${foamHeader('dictionary', 'surfaceFeatureExtractDict', 'system')}
${blocks}
${FOOTER}`;
}

/** snappyHexMeshDict: castellate + snap always, layers optional; one region per STL. */
export function renderSnappyHexMeshDict(
  stlNames: string[],
  domain: SnappyDomain,
  config: SnappyConfig,
): string {
  // `region` is the snappy name (a valid word); `emesh` is the feature file the
  // extractor actually wrote — its basename is the STL stem VERBATIM (hyphens and
  // all), so it must be referenced by the stem, not the sanitized region name.
  const regions = stlNames.map((name) => ({
    file: name,
    region: regionNameFor(name),
    emesh: `${name.replace(/\.[^.]+$/, '')}.eMesh`,
  }));
  const geometry = regions
    .map((r) => `    ${r.file} { type triSurfaceMesh; name ${r.region}; }`)
    .join('\n');
  const features = regions
    .map((r) => `        { file "${r.emesh}"; level ${config.featureLevel}; }`)
    .join('\n');
  const refinementSurfaces = regions
    .map((r) => {
      // Per-surface refinement (keyed by the STL file name) overrides the default.
      const level = config.surfaceRefinements?.[r.file] ?? config.surfaceRefinement;
      return `        ${r.region} { level (${level.min} ${level.max}); }`;
    })
    .join('\n');
  // Layers grow only on the chosen surfaces (the selected boundaries); an omitted
  // or empty list means every surface, so a legacy config still layers all walls.
  const chosen = config.addLayers.surfaces;
  const layerRegions =
    chosen && chosen.length > 0 ? regions.filter((r) => chosen.includes(r.file)) : regions;
  const layers = layerRegions
    .map((r) => `        ${r.region} { nSurfaceLayers ${config.addLayers.nLayers}; }`)
    .join('\n');
  const [lx, ly, lz] = domain.locationInMesh;

  return `${foamHeader('dictionary', 'snappyHexMeshDict', 'system')}
castellatedMesh true;
snap            true;
addLayers       ${config.addLayers.enabled ? 'true' : 'false'};

geometry
{
${geometry}
}

castellatedMeshControls
{
    maxLocalCells       1000000;
    maxGlobalCells      5000000;
    minRefinementCells  10;
    nCellsBetweenLevels 3;
    maxLoadUnbalance    0.10;
    resolveFeatureAngle 30;
    allowFreeStandingZoneFaces true;

    features
    (
${features}
    );

    refinementSurfaces
    {
${refinementSurfaces}
    }

    refinementRegions {}

    locationInMesh (${fmt(lx)} ${fmt(ly)} ${fmt(lz)});
}

snapControls
{
    nSmoothPatch        3;
    tolerance           2.0;
    nSolveIter          30;
    nRelaxIter          5;
    nFeatureSnapIter    10;
    implicitFeatureSnap false;
    explicitFeatureSnap true;
    multiRegionFeatureSnap false;
}

addLayersControls
{
    relativeSizes       ${config.addLayers.relativeSizes ? 'true' : 'false'};
    layers
    {
${layers}
    }
    expansionRatio      ${fmt(config.addLayers.expansionRatio)};
    finalLayerThickness ${fmt(config.addLayers.finalLayerThickness)};
    minThickness        ${fmt(minLayerThickness(config.addLayers))};
    nGrow               0;
    featureAngle        60;
    slipFeatureAngle    30;
    nRelaxIter          3;
    nSmoothSurfaceNormals 1;
    nSmoothNormals      3;
    nSmoothThickness    10;
    maxFaceThicknessRatio 0.5;
    maxThicknessToMedialRatio 0.3;
    minMedialAxisAngle  90;
    nBufferCellsNoExtrude 0;
    nLayerIter          50;
}

meshQualityControls
{
    maxNonOrtho         65;
    maxBoundarySkewness 20;
    maxInternalSkewness 4;
    maxConcave          80;
    minVol              1e-13;
    minTetQuality       1e-15;
    minArea             -1;
    minTwist            0.02;
    minDeterminant      0.001;
    minFaceWeight       0.02;
    minVolRatio         0.01;
    minTriangleTwist    -1;
    nSmoothScale        4;
    errorReduction      0.75;
}

writeFlags ( scalarLevels layerSets layerFields );
mergeTolerance 1e-6;
${FOOTER}`;
}
