// Pure string renderers for the OpenFOAM dictionaries a meshing run generates.
//
// Kept separate from openfoamCase.ts (whose base files are solver-oriented):
// snappyHexMesh needs mesh-only variants — controlDict with `application
// snappyHexMesh`, a background blockMeshDict sized from the STL bounds, a
// surfaceFeatureExtractDict, and the snappyHexMeshDict itself. Everything is a
// pure function of the STL bounds + the user's SnappyConfig, so the whole set is
// computed (and unit-tested) with no OpenFOAM toolchain present.
import type { AddLayersConfig, DomainType, MeshBounds, SnappyConfig } from '@dive/shared';

/**
 * A sensible `minThickness` for the layer controls: a quarter of the final layer
 * thickness. In relative mode that is a small fraction of the cell; in absolute
 * mode a small length — either way below the layer that must be grown.
 */
function minLayerThickness(layers: AddLayersConfig): number {
  return Math.max(layers.finalLayerThickness * 0.25, 1e-6);
}

/** Standard OpenFOAM dictionary banner + FoamFile header. */
function foamHeader(className: string, object: string, location: string): string {
  return `/*--------------------------------*- C++ -*----------------------------------*\\
| =========                 |                                                 |
| \\\\      /  F ield         | OpenFOAM: The Open Source CFD Toolbox           |
|  \\\\    /   O peration     | Generated by DIVE Turbinen (meshing session)    |
|   \\\\  /    A nd           |                                                 |
|    \\\\/     M anipulation  |                                                 |
\\*---------------------------------------------------------------------------*/
FoamFile
{
    version     2.0;
    format      ascii;
    class       ${className};
    location    "${location}";
    object      ${object};
}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //
`;
}

const FOOTER = `
// ************************************************************************* //
`;

/** A region name for an STL: its basename stem reduced to a valid OpenFOAM word. */
export function regionNameFor(stlFileName: string): string {
  const stem = stlFileName.replace(/\.[^.]+$/, '');
  const word = stem.replace(/[^A-Za-z0-9_]+/g, '_').replace(/^_+|_+$/g, '');
  return word || 'surface';
}

/** The resolved background-box geometry + keep-point for a run. */
export interface SnappyDomain {
  boxMin: [number, number, number];
  boxMax: [number, number, number];
  counts: [number, number, number];
  cellSize: number;
  locationInMesh: [number, number, number];
}

/** Euclidean length of the bbox diagonal. */
function diagonal(bounds: MeshBounds): number {
  const dx = bounds.max[0] - bounds.min[0];
  const dy = bounds.max[1] - bounds.min[1];
  const dz = bounds.max[2] - bounds.min[2];
  return Math.sqrt(dx * dx + dy * dy + dz * dz);
}

/** Clamp a cell count into a sane range (never 0; guard against a runaway tiny cell). */
function clampCount(n: number): number {
  if (!Number.isFinite(n) || n < 1) return 1;
  return Math.min(500, Math.round(n));
}

/**
 * Resolve the background box, cell counts, and keep-point from the STL bounds and
 * the config. `baseCellSize`/`locationInMesh` null means "derive here":
 *  - cell size defaults to bbox-diagonal / 40 (a reasonable coarse base);
 *  - the box is the bbox padded by marginFactor * diagonal on every side;
 *  - the keep-point is the bbox centre (internal) or a padded-box corner (external).
 */
export function computeDomain(bounds: MeshBounds, config: SnappyConfig): SnappyDomain {
  const diag = diagonal(bounds) || 1;
  const cellSize = config.baseCellSize && config.baseCellSize > 0 ? config.baseCellSize : diag / 40;
  const pad = Math.max(0, config.marginFactor) * diag;

  const boxMin: [number, number, number] = [
    bounds.min[0] - pad,
    bounds.min[1] - pad,
    bounds.min[2] - pad,
  ];
  const boxMax: [number, number, number] = [
    bounds.max[0] + pad,
    bounds.max[1] + pad,
    bounds.max[2] + pad,
  ];
  const counts: [number, number, number] = [
    clampCount((boxMax[0] - boxMin[0]) / cellSize),
    clampCount((boxMax[1] - boxMin[1]) / cellSize),
    clampCount((boxMax[2] - boxMin[2]) / cellSize),
  ];

  const locationInMesh = config.locationInMesh ?? defaultLocationInMesh(bounds, boxMin, config.domainType);

  return { boxMin, boxMax, counts, cellSize, locationInMesh };
}

/**
 * The auto keep-point: the bbox centre for an internal domain (inside the closed
 * surface → snappy keeps the interior), or a corner of the padded box for an
 * external domain (guaranteed outside the surface, since the box extends past the
 * bbox → snappy keeps the exterior). Both are user-overridable in the UI.
 */
function defaultLocationInMesh(
  bounds: MeshBounds,
  boxMin: [number, number, number],
  domainType: DomainType,
): [number, number, number] {
  if (domainType === 'external') {
    // Nudge just inside the box corner so the point is strictly interior to the box.
    const eps = [
      (bounds.min[0] - boxMin[0]) * 0.01,
      (bounds.min[1] - boxMin[1]) * 0.01,
      (bounds.min[2] - boxMin[2]) * 0.01,
    ];
    return [boxMin[0] + eps[0], boxMin[1] + eps[1], boxMin[2] + eps[2]];
  }
  return [
    (bounds.min[0] + bounds.max[0]) / 2,
    (bounds.min[1] + bounds.max[1]) / 2,
    (bounds.min[2] + bounds.max[2]) / 2,
  ];
}

/** Format a number for a dict (avoid scientific-notation surprises, trim noise). */
function fmt(n: number): string {
  if (!Number.isFinite(n)) return '0';
  // Six significant figures is plenty for mesh coordinates and keeps dicts tidy.
  return Number(n.toPrecision(6)).toString();
}

/** controlDict for the mesh utilities (application snappyHexMesh; one time step). */
export function renderMeshingControlDict(): string {
  return `${foamHeader('dictionary', 'controlDict', 'system')}
application     snappyHexMesh;
startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         1;
deltaT          1;
writeControl    timeStep;
writeInterval   1;
purgeWrite      0;
writeFormat     ascii;
writePrecision  6;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable true;
${FOOTER}`;
}

