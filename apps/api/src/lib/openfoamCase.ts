// OpenFOAM case domain helpers: the canonical list of mandatory files, the
// generic-minimal templates used to scaffold the missing base files, and a
// tolerant parser for the mesh boundary patch names.
//
// Scope (v1): purely textual generation. We do NOT presume a specific solver,
// so the generated dictionaries are deliberately minimal, generic, and meant to
// be edited. The only knowledge we inject from the imported mesh is the set of
// boundary patch names, so the generated 0/ fields already reference the right
// patches (the rule that 0/*.boundaryField must cover every polyMesh patch).
//
// See docs/openfoam-fichiers-obligatoires.md for the contract this encodes.
