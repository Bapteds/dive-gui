/**
 * Read the solver name from a controlDict's `application` keyword, or null when
 * absent/unparseable. Tolerant: ignores comments before the keyword.
 */
export function parseApplication(controlDictContent: string): string | null {
  const cleaned = controlDictContent
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/.*$/gm, '');
  const match = cleaned.match(/\bapplication\s+([A-Za-z_][A-Za-z0-9_]*)\s*;/);
  return match ? match[1] : null;
}

/**
 * Read the turbulence model from a constant/turbulenceProperties text: the
 * RAS.RASModel or LES.LESModel token, or 'laminar' when simulationType is laminar.
 * Null when unparseable. Tolerant of comments. Lets the generator recover the case's
 * current model (e.g. on a "change solver" call that carries no explicit model) so
 * it writes exactly the right 0/ turbulence fields and wall functions.
 */
export function parseTurbulenceModel(content: string): string | null {
  const cleaned = content.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
  if (/\bsimulationType\s+laminar\s*;/.test(cleaned)) return 'laminar';
  const ras = cleaned.match(/\bRASModel\s+([A-Za-z_][A-Za-z0-9_]*)\s*;/);
  if (ras) return ras[1];
  const les = cleaned.match(/\bLESModel\s+([A-Za-z_][A-Za-z0-9_]*)\s*;/);
  if (les) return les[1];
  return null;
}

/**
 * Set the `application` keyword in a controlDict to `solver`. Replaces an
 * existing `application <x>;` line (preserving indentation); if none is present,
 * inserts one just after the FoamFile header banner. Used by "Make runnable for
 * simpleFoam" so a case scaffolded generically (`application foamRun`) actually
 * targets the solver its turbulence/transport files are written for.
 */
export function setApplication(content: string, solver: string): string {
  if (/^[ \t]*application[ \t]+[A-Za-z_][A-Za-z0-9_]*[ \t]*;/m.test(content)) {
    return content.replace(
      /^([ \t]*)application[ \t]+[A-Za-z_][A-Za-z0-9_]*[ \t]*;/m,
      `$1application     ${solver};`,
    );
  }
  const line = `application     ${solver};`;
  const banner = content.indexOf('// * * *');
  if (banner >= 0) {
    const newline = content.indexOf('\n', banner);
    if (newline >= 0) {
      return `${content.slice(0, newline + 1)}\n${line}\n${content.slice(newline + 1)}`;
    }
  }
  return `${line}\n${content}`;
}

// ---------------------------------------------------------------------------
// Sync boundaryField to the mesh boundary (names + types).
//
// When a polyMesh is imported and then scaffolded or a template is applied, the
// 0/ fields' boundaryField may not match the mesh's patches (a template brings
// its own patch names; the scaffold ignores the geometric type). This rebuilds
// every field's boundaryField to cover exactly the mesh patches, with a valid BC
// per geometric type: a constraint type (empty/symmetry/symmetryPlane/wedge) is
// mirrored (required), a wall gets noSlip (U), zeroGradient (p) or the turbulence
// model's wall function (nut/k/epsilon/omega, …), and a plain patch gets
// zeroGradient (the user sets inlet/outlet specifics afterwards).
// ---------------------------------------------------------------------------

/** One mesh boundary patch with its geometric type, read from the boundary file. */
export interface BoundaryPatch {
  name: string;
  type: string;
}

/**
 * Parse the boundary patches AND their geometric `type` from a
 * constant/polyMesh/boundary file. Like parseBoundaryPatches but also reads the
 * `type X;` inside each patch block. Order preserved, de-duplicated by name.
 */
export function parseBoundaryPatchesWithTypes(content: string): BoundaryPatch[] {
  const cleaned = content.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
  const result: BoundaryPatch[] = [];
  const seen = new Set<string>();
  const blockStart = /([A-Za-z_][A-Za-z0-9_-]*)\s*\{/g;
  let match: RegExpExecArray | null;
  while ((match = blockStart.exec(cleaned)) !== null) {
    const name = match[1];
    if (name === 'FoamFile' || seen.has(name)) continue;
    const open = cleaned.indexOf('{', match.index);
    const close = matchBrace(cleaned, open);
    if (close < 0) continue;
    const block = cleaned.slice(open, close + 1);
    const typeMatch = block.match(/\btype\s+([A-Za-z_][A-Za-z0-9_]*)\s*;/);
    result.push({ name, type: typeMatch ? typeMatch[1] : 'patch' });
    seen.add(name);
    blockStart.lastIndex = close; // skip the block body (no nested patch headers)
  }
  return result;
}

/** One mesh boundary patch with its geometric type AND boundary face count. */
export interface BoundaryPatchDetail {
  name: string;
  type: string;
  nFaces: number;
}

/**
 * Parse the boundary patches with their geometric `type` AND `nFaces` from a
 * constant/polyMesh/boundary file. Like parseBoundaryPatchesWithTypes but also
 * reads each patch's face count — used to describe a mesh source in the library
 * and merge UI (where face counts help pick the right interface patch). Order
 * preserved, de-duplicated by name.
 */
export function parseBoundaryPatchDetails(content: string): BoundaryPatchDetail[] {
  const cleaned = content.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
  const result: BoundaryPatchDetail[] = [];
  const seen = new Set<string>();
  const blockStart = /([A-Za-z_][A-Za-z0-9_-]*)\s*\{/g;
  let match: RegExpExecArray | null;
  while ((match = blockStart.exec(cleaned)) !== null) {
    const name = match[1];
    if (name === 'FoamFile' || seen.has(name)) continue;
    const open = cleaned.indexOf('{', match.index);
    const close = matchBrace(cleaned, open);
    if (close < 0) continue;
    const block = cleaned.slice(open, close + 1);
    const typeMatch = block.match(/\btype\s+([A-Za-z_][A-Za-z0-9_]*)\s*;/);
    const nFacesMatch = block.match(/\bnFaces\s+(\d+)\s*;/);
    result.push({
      name,
      type: typeMatch ? typeMatch[1] : 'patch',
      nFaces: nFacesMatch ? Number(nFacesMatch[1]) : 0,
    });
    seen.add(name);
    blockStart.lastIndex = close;
  }
  return result;
}

/** Render a fresh boundaryField block covering exactly `patches` for `fieldName`,
 * with the model-aware wall function on any `wall` patch (see fieldBcBody). */
function renderBoundaryFieldFor(
  fieldName: string,
  patches: BoundaryPatch[],
  model?: string,
): string {
  if (patches.length === 0) return 'boundaryField\n{\n}';
  const entries = patches
    .map(
      (patch) => `    ${patch.name}
    {
        ${fieldBcBody(fieldName, patch.type, model)}
    }`,
    )
    .join('\n');
  return `boundaryField\n{\n${entries}\n}`;
}

/**
 * Rebuild a field file's `boundaryField` block so it covers exactly the mesh
 * patches with a valid BC per geometric type. Replaces the whole existing block
 * (the action is an explicit "apply the boundary to the fields"); the rest of
 * the file (header, dimensions, internalField) is untouched. Returns the content
 * unchanged when the file has no boundaryField. `fieldName` is the field's object
 * name (e.g. "U", "p", "k") used to pick a sensible per-field default.
 */
export function rebuildFieldBoundary(
  content: string,
  fieldName: string,
  patches: BoundaryPatch[],
  model?: string,
): string {
  const span = boundaryFieldSpan(content);
  const keyword = content.search(/\bboundaryField\b/);
  if (!span || keyword < 0) return content;
  return (
    content.slice(0, keyword) +
    renderBoundaryFieldFor(fieldName, patches, model) +
    content.slice(span.close + 1)
  );
}

/**
 * One entry inside a field file's `boundaryField` block: its selector `name` (a
 * plain patch name, or a quoted regex group like `".*"`), the exact source `text`
 * of the `name { … }` block, and whether the selector is a plain patch name (vs a
 * regex group that may match several patches and must never be dropped).
 */
interface FieldBoundaryEntry {
  name: string;
  text: string;
  plain: boolean;
}

/** Split a boundaryField block's inner text into its `name { … }` entries. */
function parseFieldBoundaryEntries(inner: string): FieldBoundaryEntry[] {
  const entries: FieldBoundaryEntry[] = [];
  // A selector is a quoted regex ("...") or a plain word (patch name); it is the
  // token immediately before `{`. Values (e.g. `type X;`) carry no `{`, so are
  // skipped. Patch names may contain hyphens (Fluent zones), matched here too.
  const headerRe = /("(?:[^"\\]|\\.)*"|[A-Za-z_][A-Za-z0-9_-]*)\s*\{/g;
  let match: RegExpExecArray | null;
  while ((match = headerRe.exec(inner)) !== null) {
    const name = match[1];
    const open = inner.indexOf('{', match.index);
    const close = matchBrace(inner, open);
    if (close < 0) break;
    entries.push({ name, text: inner.slice(match.index, close + 1), plain: !name.startsWith('"') });
    headerRe.lastIndex = close + 1; // skip the entry body (its BC may hold braces)
  }
  return entries;
}

/**
 * MERGE a field file's `boundaryField` against the mesh patches, PRESERVING the
 * user's physics: every existing entry whose patch still exists is kept verbatim
 * (so e.g. an `inlet { type fixedValue; … }` survives), a stale plain entry whose
 * patch is gone is dropped, a quoted/regex group entry is always kept (it may
 * match several patches), and a generic default entry is ADDED only for a mesh
 * patch that has no matching entry yet — constraint types and wall functions
 * resolved via fieldBcBody. A kept entry whose patch is now a CONSTRAINT type (e.g. a base
 * `outlet` the Assembly non-conformal couple retyped in place to cyclicAMI) has
 * its field BC RESET to that exact type, because the solver requires a constraint
 * patch's field BC to match its geometric type — a stale non-matching BC (like a
 * leftover zeroGradient) would otherwise error at runtime. Returns the content
 * unchanged when the file has no boundaryField. Counterpart to rebuildFieldBoundary
 * (which DISCARDS the existing BCs): used when merging onto the project case mesh
 * so the base's boundary conditions are not reset to generic defaults.
 */
export function mergeFieldBoundary(
  content: string,
  fieldName: string,
  patches: BoundaryPatch[],
  model?: string,
): string {
  const span = boundaryFieldSpan(content);
  const keyword = content.search(/\bboundaryField\b/);
  if (!span || keyword < 0) return content;

  const inner = content.slice(span.open + 1, span.close);
  const existing = parseFieldBoundaryEntries(inner);
  const patchNames = new Set(patches.map((patch) => patch.name));
  const typeByName = new Map(patches.map((patch) => [patch.name, patch.type] as const));

  const kept: string[] = [];
  const keptPlain = new Set<string>();
  for (const entry of existing) {
    if (!entry.plain) {
      kept.push(entry.text); // a regex/group selector may match several patches
      continue;
    }
    if (patchNames.has(entry.name)) {
      const geometricType = typeByName.get(entry.name)!;
      if ((CONSTRAINT_PATCH_TYPES as readonly string[]).includes(geometricType)) {
        // The patch was (re)typed to a constraint type (e.g. cyclicAMI): the field
        // BC must match it exactly, so reset the kept entry to the constraint type.
        kept.push(`${entry.name}
    {
        ${fieldBcBody(fieldName, geometricType, model)}
    }`);
      } else {
        kept.push(entry.text);
      }
      keptPlain.add(entry.name);
    }
    // else: a plain entry for a patch that no longer exists -> drop it.
  }

  // ADD a generic default only for a mesh patch that has no exact entry yet.
  const added = patches
    .filter((patch) => !keptPlain.has(patch.name))
    .map(
      (patch) => `${patch.name}
    {
        ${fieldBcBody(fieldName, patch.type, model)}
    }`,
    );

  const body = [...kept, ...added].map((entry) => `    ${entry}`).join('\n');
  return content.slice(0, keyword) + `boundaryField\n{\n${body}\n}` + content.slice(span.close + 1);
}

/** A valid OpenFOAM patch name: a "word" token starting with a letter/underscore,
 * then letters/digits/underscore/HYPHEN. Hyphens are common in Fluent .msh zone
 * names (e.g. `velocity-inlet`, `wall-1`) and are valid OpenFOAM words, so they are
 * allowed here to match what the boundary parser already accepts. */
const PATCH_NAME_RE = /^[A-Za-z_][A-Za-z0-9_-]*$/;

/** Is `name` a syntactically valid OpenFOAM patch name? */
export function isValidPatchName(name: string): boolean {
  return PATCH_NAME_RE.test(name);
}

/** Escape a string for safe use inside a RegExp. */
function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Replace a patch block header `from { … }` with `to { … }`. A patch name is the
 * only token immediately followed (across optional whitespace/newlines) by `{`,
 * so this targets the dictionary header and never a value like `type from;` or a
 * group reference `1(from)`. The preceding delimiter (start / whitespace / `(`)
 * is preserved.
 */
function renamePatchHeader(content: string, from: string, to: string): string {
  const re = new RegExp(`(^|[\\s(])${escapeRegExp(from)}(\\s*\\{)`, 'g');
  return content.replace(re, `$1${to}$2`);
}

/**
 * Rename a patch in a constant/polyMesh/boundary file. The only `name { … }`
 * blocks there are the patch entries (the FoamFile header is named `FoamFile`),
 * so a whole-file header rename is safe.
 */
export function renameBoundaryPatch(content: string, from: string, to: string): string {
  return renamePatchHeader(content, from, to);
}

/** The standard polyBoundaryMesh FoamFile header, used when none can be preserved. */
const BOUNDARY_FOAMFILE_HEADER = `FoamFile
{
    version     2.0;
    format      ascii;
    class       polyBoundaryMesh;
    location    "constant/polyMesh";
    object      boundary;
}`;

/**
 * Collapse every boundary patch into a SINGLE patch that covers all boundary
 * faces. The boundary faces are the contiguous tail of the mesh face list and
 * the patches partition them with no gaps, so one patch with
 * `startFace = min(startFace)` and `nFaces = sum(nFaces)` is valid and covers
 * exactly the same faces.
 *
 * This exists for re-running OpenFOAM's autoPatch: autoPatch keeps the existing
 * patches in its output and appends fresh `autoN` patches, so re-running it on an
 * already-patched mesh accumulates stale (0-face) patches and the numbering keeps
 * climbing. Collapsing to one patch first makes each run start from a clean slate
 * and number from `auto0` again. Returns the content unchanged when no patch with
 * an nFaces/startFace pair is found.
 */
export function collapseBoundaryToSinglePatch(content: string, patchName = 'defaultFaces'): string {
  const nFaces = [...content.matchAll(/\bnFaces\s+(\d+)/g)].map((m) => Number(m[1]));
  const startFaces = [...content.matchAll(/\bstartFace\s+(\d+)/g)].map((m) => Number(m[1]));
  if (nFaces.length === 0 || startFaces.length === 0) return content;

  const total = nFaces.reduce((sum, n) => sum + n, 0);
  const start = Math.min(...startFaces);
  const headerMatch = content.match(/FoamFile\s*\{[^}]*\}/);
  const header = headerMatch ? headerMatch[0] : BOUNDARY_FOAMFILE_HEADER;

  return (
    `${header}\n\n1\n(\n` +
    `    ${patchName}\n    {\n        type            patch;\n` +
    `        nFaces          ${total};\n        startFace       ${start};\n    }\n)\n`
  );
}

/**
 * Drop every boundary patch with zero faces (`nFaces 0`) and renumber the patch
 * count. autoPatch leaves the pre-existing patches behind as empty entries; this
 * removes them so only the real, populated patches remain. Patch blocks in a
 * boundary file contain no nested braces (groups use parentheses), so a
 * non-greedy `{…}` match is safe. Returns the content unchanged when nothing is
 * empty (or it cannot be parsed).
 */
export function removeEmptyBoundaryPatches(content: string): string {
  const headerMatch = content.match(/FoamFile\s*\{[^}]*\}/);
  if (!headerMatch) return content;
  const header = headerMatch[0];
  const body = content.slice(headerMatch.index! + header.length);

  // Patch names may contain hyphens (Fluent .msh zone names routinely do, e.g.
  // "wall-1"); match the same char class as parseBoundaryPatchDetails so a
  // hyphenated populated patch is kept, not silently dropped from the rewrite.
  const blockRe = /([A-Za-z_][A-Za-z0-9_-]*)\s*\{[^{}]*\}/g;
  const kept: string[] = [];
  let removed = 0;
  let match: RegExpExecArray | null;
  while ((match = blockRe.exec(body)) !== null) {
    const block = match[0];
    const nf = block.match(/\bnFaces\s+(\d+)/);
    if (nf && Number(nf[1]) === 0) {
      removed += 1;
      continue;
    }
    kept.push(block.trim());
  }
  if (removed === 0) return content;

  const list = kept.map((block) => `    ${block}`).join('\n');
  return `${header}\n\n${kept.length}\n(\n${list}\n)\n`;
}

/**
 * Find the brace span of the `boundaryField { … }` dictionary in a field file,
 * or null when absent. Brace-matched from the first `{` after the keyword.
 */
function boundaryFieldSpan(content: string): { open: number; close: number } | null {
  const keyword = content.search(/\bboundaryField\b/);
  if (keyword < 0) return null;
  const open = content.indexOf('{', keyword);
  if (open < 0) return null;
  let depth = 0;
  for (let i = open; i < content.length; i += 1) {
    const char = content[i];
    if (char === '{') depth += 1;
    else if (char === '}') {
      depth -= 1;
      if (depth === 0) return { open, close: i };
    }
  }
  return null;
}

/**
 * Rename a patch entry inside a field file's `boundaryField` block only (so a
 * patch name that happens to appear elsewhere — a coded `functions` block, a
 * comment — is left untouched). Returns the content unchanged when the file has
 * no boundaryField.
 */
export function renameFieldBoundaryPatch(content: string, from: string, to: string): string {
  const span = boundaryFieldSpan(content);
  if (!span) return content;
  const before = content.slice(0, span.open);
  const block = content.slice(span.open, span.close + 1);
  const after = content.slice(span.close + 1);
  return before + renamePatchHeader(block, from, to) + after;
}

/** Index of the `}` matching the `{` at `open`, or -1 when unbalanced. */
function matchBrace(content: string, open: number): number {
  let depth = 0;
  for (let i = open; i < content.length; i += 1) {
    const char = content[i];
    if (char === '{') depth += 1;
    else if (char === '}') {
      depth -= 1;
      if (depth === 0) return i;
    }
  }
  return -1;
}

/**
 * Set the `type` of a patch block in a constant/polyMesh/boundary file. Targets
 * the patch's own dictionary header (`name { … }`), replacing its `type X;` (or
 * inserting one if absent). Returns the content unchanged when the patch is
 * absent. A patch name appearing as a value (`type name;`) is never matched
 * because the header requires the name to be immediately followed by `{`.
 */
export function setBoundaryPatchType(content: string, patch: string, type: string): string {
  const header = new RegExp(`(?:^|[\\s(])${escapeRegExp(patch)}\\s*\\{`, 'm');
  const match = header.exec(content);
  if (!match) return content;
  const open = content.indexOf('{', match.index);
  const close = matchBrace(content, open);
  if (close < 0) return content;

  const block = content.slice(open, close + 1);
  const retyped = block.replace(/(\btype\s+)[A-Za-z_][A-Za-z0-9_]*(\s*;)/, `$1${type}$2`);
  const next = retyped !== block ? retyped : block.replace('{', `{\n        type            ${type};`);
  return content.slice(0, open) + next + content.slice(close + 1);
}

/**
 * Retype ONE boundary patch to `cyclicAMI`, coupled to `neighbour`, in a
 * constant/polyMesh/boundary file. The patch KEEPS its name, `nFaces` and
 * `startFace` (its faces are untouched); its dictionary body is rewritten to a
 * clean cyclicAMI block: `type cyclicAMI;` + `neighbourPatch <neighbour>;` +
 * `transform noOrdering;`. Any prior `type` / `neighbourPatch` / `transform` /
 * `matchTolerance` keys are replaced (the block is rebuilt from its face slice),
 * so re-coupling an already-coupled patch is idempotent. Returns the content
 * unchanged when the patch is absent. Pure text — no I/O.
 */
function setBoundaryPatchCyclicAmi(content: string, patch: string, neighbour: string): string {
  const header = new RegExp(`(?:^|[\\s(])${escapeRegExp(patch)}\\s*\\{`, 'm');
  const match = header.exec(content);
  if (!match) return content;
  const open = content.indexOf('{', match.index);
  const close = matchBrace(content, open);
  if (close < 0) return content;

  const inner = content.slice(open + 1, close);
  const nFaces = inner.match(/\bnFaces\s+(\d+)/);
  const startFace = inner.match(/\bstartFace\s+(\d+)/);
  const body =
    `\n        type            cyclicAMI;` +
    (nFaces ? `\n        nFaces          ${nFaces[1]};` : '') +
    (startFace ? `\n        startFace       ${startFace[1]};` : '') +
    `\n        neighbourPatch  ${neighbour};` +
    `\n        transform       noOrdering;\n    `;
  return content.slice(0, open + 1) + body + content.slice(close);
}

/**
 * Couple two touching interface patches NON-conformally by retyping BOTH to
 * `cyclicAMI` in a constant/polyMesh/boundary file, cross-linked via
 * `neighbourPatch` (`aPatch` -> `bPatch` and back) with `transform noOrdering`.
 * Both patches keep their names, `nFaces` and `startFace`; the AMI weights are
 * computed by the solver at runtime, so only geometric overlap is required. This
 * is the ESI-compatible, in-process replacement for the org-only
 * `createNonConformalCouples` utility (Assembly v3). Pure text — no I/O, no CLI —
 * so it is fully unit-testable and flavour-independent. Returns the content
 * unchanged for any patch that is absent.
 */
export function setCyclicAmiPair(content: string, aPatch: string, bPatch: string): string {
  const withA = setBoundaryPatchCyclicAmi(content, aPatch, bPatch);
  return setBoundaryPatchCyclicAmi(withA, bPatch, aPatch);
}

/** Read the BC `type` of a patch entry inside a field's boundaryField, or null. */
export function getFieldPatchType(content: string, patch: string): string | null {
  const span = boundaryFieldSpan(content);
  if (!span) return null;
  const block = content.slice(span.open, span.close + 1);
  const header = new RegExp(`(?:^|[\\s])${escapeRegExp(patch)}\\s*\\{`, 'm');
  const match = header.exec(block);
  if (!match) return null;
  const open = block.indexOf('{', match.index);
  const close = matchBrace(block, open);
  if (close < 0) return null;
  const entry = block.slice(open, close + 1);
  const typeMatch = entry.match(/\btype\s+([A-Za-z_][A-Za-z0-9_]*)\s*;/);
  return typeMatch ? typeMatch[1] : null;
}

/**
 * Replace a patch entry inside a field's boundaryField with a minimal
 * `{ type <bcType>; }`. Used to propagate a constraint patch type (empty /
 * symmetry / …) into the 0/ fields, where the field BC must match the geometric
 * type exactly (those BCs take no other keywords). Returns content unchanged when
 * the field has no boundaryField or no such patch entry.
 */
export function setFieldPatchType(content: string, patch: string, bcType: string): string {
  const span = boundaryFieldSpan(content);
  if (!span) return content;
  const block = content.slice(span.open, span.close + 1);
  const header = new RegExp(`(?:^|[\\s])${escapeRegExp(patch)}\\s*\\{`, 'm');
  const match = header.exec(block);
  if (!match) return content;
  const open = block.indexOf('{', match.index);
  const close = matchBrace(block, open);
  if (close < 0) return content;
  const entry = `{\n        type            ${bcType};\n    }`;
  const newBlock = block.slice(0, open) + entry + block.slice(close + 1);
  return content.slice(0, span.open) + newBlock + content.slice(span.close + 1);
}

/**
 * Replace a patch entry inside a field's boundaryField with a multi-line `body`
 * (the `type …;` plus any `value …;` a wall function carries). Like setFieldPatchType
 * but for bodies richer than a bare type — used to propagate a wall patch's
 * model-aware wall function (see fieldBcBody) into the 0/ fields when the user
 * retypes a patch to `wall`. Returns content unchanged when the field has no
 * boundaryField or no such patch entry.
 */
export function setFieldPatchBc(content: string, patch: string, body: string): string {
  const span = boundaryFieldSpan(content);
  if (!span) return content;
  const block = content.slice(span.open, span.close + 1);
  const header = new RegExp(`(?:^|[\\s])${escapeRegExp(patch)}\\s*\\{`, 'm');
  const match = header.exec(block);
  if (!match) return content;
  const open = block.indexOf('{', match.index);
  const close = matchBrace(block, open);
  if (close < 0) return content;
  const entry = `{\n        ${body}\n    }`;
  const newBlock = block.slice(0, open) + entry + block.slice(close + 1);
  return content.slice(0, span.open) + newBlock + content.slice(span.close + 1);
}

/**
 * The second-turbulence-quantity fields whose inlet is a mixing-length BC, and the
 * exact inlet type each uses (from the templates): omega uses a FREQUENCY inlet,
 * epsilon a DISSIPATION-RATE inlet. Both carry a `mixingLength`, which is what makes
 * translating between them meaningful.
 */
export const MIXING_LENGTH_INLET_FIELDS = ['omega', 'epsilon'] as const;
export type MixingLengthInletField = (typeof MIXING_LENGTH_INLET_FIELDS)[number];
const MIXING_LENGTH_INLET_TYPE: Record<MixingLengthInletField, string> = {
  omega: 'turbulentMixingLengthFrequencyInlet',
  epsilon: 'turbulentMixingLengthDissipationRateInlet',
};

/**
 * Carry a mixing-length inlet across a k-omega <-> k-epsilon model switch. When the
 * turbulence model changes, the second turbulence quantity changes too (omega <->
 * epsilon) and the new field is generated with a generic inlet. This rewrites, on
 * the NEW field's `content`, every patch that carried the SIBLING's mixing-length
 * inlet (read from `siblingContent`) to the new field's own mixing-length inlet
 * TYPE, preserving the user's `mixingLength`. So an inlet configured as
 * turbulentMixingLengthFrequencyInlet (omega) becomes
 * turbulentMixingLengthDissipationRateInlet (epsilon) and vice versa. Any patch
 * whose sibling BC is not a mixing-length inlet is left as the generic default.
 */
export function carryTurbulenceInlet(
  content: string,
  newField: MixingLengthInletField,
  siblingContent: string,
  siblingField: MixingLengthInletField,
): string {
  const sourceType = MIXING_LENGTH_INLET_TYPE[siblingField];
  const targetType = MIXING_LENGTH_INLET_TYPE[newField];
  const span = boundaryFieldSpan(siblingContent);
  if (!span) return content;
  const entries = parseFieldBoundaryEntries(siblingContent.slice(span.open + 1, span.close));
  // The new field's own internalField seed for the entry's `value`.
  const seed = newField === 'omega' ? '1' : '0.1';
  let next = content;
  for (const entry of entries) {
    if (!entry.plain) continue;
    const typeMatch = entry.text.match(/\btype\s+([A-Za-z_][A-Za-z0-9_:]*)\s*;/);
    if (!typeMatch || typeMatch[1] !== sourceType) continue;
    const mlMatch = entry.text.match(/\bmixingLength\s+([^;]+);/);
    const mixingLength = mlMatch ? mlMatch[1].trim() : '0.01';
    const body = assembleBcBody([
      ['type', targetType],
      ['mixingLength', mixingLength],
      ['value', `uniform ${seed}`],
    ]);
    next = setFieldPatchBc(next, entry.name, body);
  }
  return next;
}

/**
 * Parse the names of the boundary patches from a constant/polyMesh/boundary
 * file. Tolerant by design: strips comments, then collects every `name { ... }`
 * block in the file (excluding the FoamFile header). De-duplicated, order
 * preserved. Returns [] for unparhseable or empty input.
 */
export function parseBoundaryPatches(content: string): string[] {
  const withoutBlockComments = content.replace(/\/\*[\s\S]*?\*\//g, '');
  const cleaned = withoutBlockComments.replace(/\/\/.*$/gm, '');

  const names: string[] = [];
  const blockStart = /([A-Za-z_][A-Za-z0-9_-]*)\s*\{/g;
  let match: RegExpExecArray | null;
  while ((match = blockStart.exec(cleaned)) !== null) {
    const name = match[1];
    if (name === 'FoamFile') continue;
    names.push(name);
  }
  return [...new Set(names)];
}
